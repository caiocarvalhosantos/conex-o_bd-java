    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        rm = Integer.parseInt(jTextField1.getText());
        nome = jTextField2.getText();
        idade = Integer.parseInt(jTextField3.getText());
        
        String sql_cadastro = "INSERT INTO tb_aluno (cd_rm, nm_aluno, nr_idade) values (?, ?, ?)";
        
        try(Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/bd_java", "root", "1234");
                PreparedStatement stmt =  conn.prepareStatement(sql_cadastro)) {
            
            stmt.setString(1, String.valueOf(rm));
            stmt.setString(2, nome);
            stmt.setString(3, String.valueOf(idade));
            
            stmt.executeUpdate();
            
            System.out.println("Funcionou! Cadastrado!");
            
        }
        catch(SQLException e) {
            System.out.println("Erro: " + e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

